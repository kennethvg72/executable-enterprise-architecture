// Renders load balancer and database configuration from declared intent:
// - HAProxy for platform-lb, one file per datacenter
// - Patroni configuration for each PostgreSQL cluster
// - a vendor-neutral health check specification for the commercial edge appliances
// - the failure simulation, as Markdown
//
// Usage: node infrastructure/tools/render.ts

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT, loadModel } from '../../enterprise-architecture/tools/lib/load.ts';
import type { Model, Provide, Service } from '../../enterprise-architecture/tools/lib/model.ts';
import { SCENARIOS, renderMarkdown, simulate } from './simulate.ts';

export const GENERATED = join(REPO_ROOT, 'infrastructure', 'generated');
const HEADER = '# Generated by infrastructure/tools/render.ts from declared intent. Do not edit.\n';
const CA = '/etc/haproxy/ca/natax-workload-ca.pem';
const DOMAIN = 'natax.internal';

interface Published { service: Service; provide: Provide }

/** Everything published through a given load balancer. */
export function publishedVia(model: Model, lb: string): Published[] {
  const out: Published[] = [];
  for (const service of model.services.values()) {
    for (const provide of service.provides ?? []) if (provide.via === lb) out.push({ service, provide });
  }
  return out.sort((a, b) => a.service.id.localeCompare(b.service.id));
}

/** Per source of traffic (a zone or a service): the hostnames it may ask the shared frontend for. */
function hostLimits(model: Model, apps: Service[]): string[] {
  const allowed = new Map<string, { addresses: string[]; hosts: string[] }>();
  for (const app of apps) {
    for (const provide of (app.provides ?? []).filter((x) => x.via === 'platform-lb')) {
      for (const consumer of Array.isArray(provide.consumers) ? provide.consumers : []) {
        const zone = consumer.startsWith('zone:') ? model.landscape.zones[consumer.slice(5)] : undefined;
        const svc = zone ? undefined : model.services.get(consumer);
        const addresses = zone ? zone.cidrs : (svc?.egress ?? svc?.instances ?? []).map((i) => i.address);
        if (!addresses.length) continue;
        const entry = allowed.get(consumer) ?? { addresses, hosts: [] };
        entry.hosts.push(`${app.id}.${DOMAIN}`);
        allowed.set(consumer, entry);
      }
    }
  }
  return [...allowed].sort(([a], [b]) => a.localeCompare(b)).map(([, e]) =>
    `  http-request deny deny_status 403 if { src ${[...new Set(e.addresses)].sort().join(' ')} } !{ req.hdr(host),field(1,:) -i ${[...new Set(e.hosts)].sort().join(' ')} }`);
}

const vipOf = (model: Model, lb: string, site: string) =>
  model.services.get(lb)!.vips!.find((v) => v.site === site)!.address;

/** Servers for a backend: this datacenter's instances first; the other's only as backup. */
function servers(service: Service, port: number, site: string, options: string): string[] {
  const local = service.instances.filter((i) => i.site === site);
  const remote = service.instances.filter((i) => i.site !== site);
  return [
    ...local.map((i, n) => `  server ${i.site}-${n + 1} ${i.address}:${port} ${options}`),
    ...remote.map((i, n) => `  server ${i.site}-${n + 1} ${i.address}:${port} ${options} backup`),
  ];
}

export function renderHaproxy(model: Model, site: string): string {
  const vip = vipOf(model, 'platform-lb', site);
  const published = publishedVia(model, 'platform-lb');
  const apps = published.filter((p) => p.service.kind !== 'database-cluster');
  const databases = published.filter((p) => p.service.kind === 'database-cluster');
  const lines = [
    HEADER,
    `# platform-lb in ${site}. Internal applications and database endpoints.`,
    '',
    'global',
    '  log stdout format raw local0',
    '  maxconn 20000',
    '  ssl-default-bind-options ssl-min-ver TLSv1.3',
    '  ssl-default-server-options ssl-min-ver TLSv1.3',
    '',
    'defaults',
    '  log global',
    '  timeout connect 3s',
    '  timeout client 60s',
    '  timeout server 60s',
    '  # Readiness is checked every 2s; 3 failures take a server out, 2 successes put it back (RES-06).',
    '  default-server inter 2s fall 3 rise 2',
    '',
    '# ---- Internal applications: TLS terminated here and re-encrypted to the backend (SEC-04).',
    'frontend apps',
    '  mode http',
    `  bind ${vip}:443 ssl crt /etc/haproxy/certs/ alpn h2,http/1.1`,
    '  option forwardfor',
    '  # Health endpoints answer the load balancers, not clients: a flood of readiness calls',
    '  # from users must not become the overload. Every health check, including the global DNS',
    '  # monitors, goes straight to the instances (RES-06, RES-08).',
    '  http-request deny deny_status 404 if { path_beg /health/ }',
    '  # One address serves every application, routed by Host. Each source may only name the',
    '  # applications that list it as a consumer; the network can\'t tell them apart (SEC-02).',
    ...hostLimits(model, apps.map((p) => p.service)),
    '  # Overload: answer 503 at once rather than leave connections waiting in a queue (RES-08).',
    '  http-request return status 503 content-type text/plain string "Busy, please retry" if { fe_conn gt 4500 }',
    '  maxconn 5000',
    ...apps.map((p) => `  use_backend ${p.service.id} if { req.hdr(host),field(1,:) -i ${p.service.id}.${DOMAIN} }`),
    '  default_backend unknown-application',
    '',
  ];
  for (const { service, provide } of apps) {
    const health = provide.health!;
    lines.push(
      `backend ${service.id}`,
      '  mode http',
      '  balance leastconn',
      '  option httpchk',
      `  http-check send meth GET uri ${health.path} ver HTTP/1.1 hdr Host ${service.id}.${DOMAIN}`,
      '  http-check expect status 200',
      '  timeout queue 2s',
      // Verify the backend's certificate is for this service, not just any NATAX workload.
      ...servers(service, provide.port, site, `check${health.port !== provide.port ? ` port ${health.port}` : ''} ssl verify required ca-file ${CA} sni str(${service.id}.${DOMAIN}) verifyhost ${service.id}.${DOMAIN} maxconn 200`),
      '',
    );
  }
  lines.push(
    'backend unknown-application',
    '  mode http',
    '  http-request return status 404 content-type text/plain string "Unknown application"',
    '',
    '# ---- Database endpoints: TCP passthrough, TLS end to end. Routes only to the current',
    '# primary, as reported by Patroni; connections to a demoted primary are cut (RES-05).',
  );
  for (const { service, provide } of databases) {
    lines.push(
      `listen ${service.id}`,
      '  mode tcp',
      `  bind ${vip}:${provide['frontend-port'] ?? provide.port}`,
      '  # Database connections are long-lived and pooled; HTTP timeouts would cut them.',
      '  timeout client 30m',
      '  timeout server 30m',
      '  option httpchk',
      `  http-check send meth GET uri ${provide.health!.path}`,
      '  http-check expect status 200',
      '  default-server inter 2s fall 2 rise 2 on-marked-down shutdown-sessions',
      ...service.instances.map((i) => `  server ${i.site} ${i.address}:${provide.port} check port ${provide.health!.port} check-ssl verify required ca-file ${CA} verifyhost ${service.id}-${i.site}.${DOMAIN}`),
      '',
    );
  }
  return lines.join('\n');
}

/** Patroni's dynamic, cluster-wide settings, as YAML lines (unindented). */
function dcsSettings(cluster: Service): string[] {
  const r = cluster.replication!;
  return [
    'ttl: 30                            # longer than the WAN rerouting time (sites.md)',
    'loop_wait: 10',
    'retry_timeout: 10',
    `synchronous_mode: ${r.synchronous}`,
    `synchronous_mode_strict: ${r.strict}       # ${r.strict ? 'stop writes without a synchronous replica' : 'keep writing when the replica is lost (RES-05)'}`,
    'synchronous_node_count: 1',
    'postgresql:',
    '  use_pg_rewind: true',
    '  parameters:',
    `    max_connections: ${cluster['max-connections'] ?? 300}            # every consumer's pool fits, with a reserve (INF-05)`,
    '    synchronous_commit: "on"',
    '    ssl: "on"',
    '    ssl_min_protocol_version: TLSv1.3',
    '    archive_mode: "on"',
    `    archive_command: "pgbackrest --stanza=${cluster.id} archive-push %p"   # to both datacenters (backup-store, DAT-08)`,
  ];
}

/**
 * The settings Patroni keeps in the DCS, for the running cluster. Patroni reads bootstrap.dcs only
 * when a cluster is first created; after that, these settings change only through its API. So the
 * deployment process applies this file to the running cluster, and drift detection compares it
 * with what the cluster reports (DEL-04).
 */
export function renderPatroniDcs(cluster: Service): string {
  return [
    HEADER,
    `# Dynamic configuration of ${cluster.id}, applied to the running cluster by the deployment process:`,
    '# merged into what the cluster has, so settings Patroni keeps for itself survive:',
    `#   patronictl -c /etc/patroni/patroni.yml edit-config --apply patroni/${cluster.id}.dcs.yml --force`,
    '# After applying, and daily, GET /config on the leader must show these values (check-patroni-config.ts).',
    ...dcsSettings(cluster),
    '',
  ].join('\n');
}

export function renderPatroni(model: Model, cluster: Service): string {
  const etcd = model.services.get('etcd-quorum')!;
  const client = etcd.provides!.find((p) => p.name === 'client')!.port;
  const r = cluster.replication!;
  return [
    HEADER,
    `# Patroni settings shared by every node of ${cluster.id}. Node-specific settings`,
    '# (name, addresses) are added per node at deployment.',
    `scope: ${cluster.id}`,
    'etcd3:',
    '  protocol: https',
    `  hosts: [${etcd.instances.map((i) => `${i.address}:${client}`).join(', ')}]   # one voting member per site (RES-04)`,
    '  cacert: /etc/patroni/natax-workload-ca.pem',
    `  cert: /etc/patroni/patroni-${cluster.id}.pem`,
    `  key: /etc/patroni/patroni-${cluster.id}.key`,
    '  # Its own etcd user, which may touch only its own keys (etcd/rbac.yaml): another cluster sharing',
    '  # the quorum can\'t take its leader lock (SEC-09). Password authentication, because etcd ignores',
    '  # certificate names on the gateway Patroni talks to. The password comes from the secret store',
    '  # at deployment (PATRONI_ETCD3_PASSWORD), never from this file.',
    `  username: patroni-${cluster.id}`,
    'bootstrap:',
    `  dcs:                               # used only when the cluster is first created; afterwards patroni/${cluster.id}.dcs.yml`,
    ...dcsSettings(cluster).map((l) => `    ${l}`),
    'watchdog:',
    `  mode: ${r.watchdog}                   # fence a primary that loses its leader lock`,
    '  device: /dev/watchdog',
    '  safety_margin: 5',
    'tags:',
    `  nofailover: false                  # ${r.promote === 'synchronous-replica-only' ? 'with synchronous_mode, Patroni promotes only the synchronous replica' : r.promote}`,
    '',
  ].join('\n');
}

/**
 * pgBackRest for one cluster: WAL and backups go to the repositories in both datacenters, so the
 * surviving datacenter keeps archiving when the other is lost. If a repository can't be reached,
 * the queue limit stops WAL piling up until the primary's disk is full: archiving falls behind
 * (an alert, and point-in-time recovery has a gap) instead of the database stopping (DAT-08).
 */
export function renderPgBackRest(model: Model, cluster: Service): string {
  const repos = model.services.get('backup-store')?.instances ?? [];
  return [
    HEADER,
    `# pgBackRest for ${cluster.id} (DAT-08).`,
    '[global]',
    ...repos.flatMap((r, n) => [
      `# backup-store in ${r.site}`,
      `repo${n + 1}-host=${r.address}`,
      `repo${n + 1}-host-type=tls`,
      `repo${n + 1}-retention-full=4`,
    ]),
    'archive-async=y',
    '# Never fill the primary\'s disk waiting for a repository.',
    'archive-push-queue-max=4GiB',
    '',
    `[${cluster.id}]`,
    'pg1-path=/var/lib/postgresql/18/main',
    '',
  ].join('\n');
}

/**
 * etcd's access control: every Patroni cluster sharing the quorum has its own user, named after
 * its client certificate, with access to its own keys only (SEC-09). Applied by the deployment
 * process with etcdctl (role add, role grant-permission --prefix, user add --no-password).
 */
export function renderEtcdRbac(model: Model): string {
  const clusters = [...model.services.values()].filter((c) => c.kind === 'database-cluster' && c.replication);
  return [
    HEADER,
    '# etcd access control for the Patroni clusters that share the quorum (SEC-09). Enabling auth',
    '# needs the root user first; its password is in the secret store, used only through a PAW.',
    'auth: enabled',
    'authentication: password             # etcd ignores certificate names on its gRPC gateway',
    'roles:',
    ...clusters.flatMap((c) => [`  - role: patroni-${c.id}`, `    readwrite-prefix: /service/${c.id}/`]),
    'users:',
    '  - user: root',
    '    roles: [root]',
    ...clusters.flatMap((c) => [`  - user: patroni-${c.id}`, `    roles: [patroni-${c.id}]`]),
    '',
  ].join('\n');
}

/**
 * The VIP moves between the two HAProxy nodes in a datacenter with VRRP (keepalived, unicast,
 * so no multicast is needed). The nodes need net.ipv4.ip_nonlocal_bind=1, so HAProxy can bind
 * the VIP on the node that doesn't currently hold it. The firewall rules allow VRRP between them.
 */
export function renderKeepalived(model: Model, site: string, node: string): string {
  const lb = model.services.get('platform-lb')!;
  const vip = vipOf(model, 'platform-lb', site);
  const nodes = lb.instances.filter((i) => i.site === site).map((i) => i.address);
  const priority = nodes.indexOf(node) === 0 ? 150 : 100;
  return [
    HEADER,
    `# keepalived for platform-lb node ${node} in ${site}.`,
    'vrrp_script haproxy_alive {',
    '  script "/usr/bin/killall -0 haproxy"   # move the VIP if HAProxy dies',
    '  interval 2',
    '  fall 2',
    '  rise 2',
    '}',
    '',
    `vrrp_instance platform_lb_${site} {`,
    '  state BACKUP',
    '  nopreempt',
    '  interface eth0',
    `  virtual_router_id ${site === 'dc1' ? 51 : 52}`,
    '  advert_int 1',
    `  priority ${priority}`,
    `  unicast_src_ip ${node}`,
    '  unicast_peer {',
    ...nodes.filter((n) => n !== node).map((n) => `    ${n}`),
    '  }',
    '  virtual_ipaddress {',
    `    ${vip}/24`,
    '  }',
    '  track_script {',
    '    haproxy_alive',
    '  }',
    '}',
    '',
  ].join('\n');
}

/** The commercial edge appliances get the same intent, in vendor-neutral form (SIM-04). */
export function renderEdgeSpec(model: Model): string {
  const lines = [
    HEADER,
    '# Health checks and global load balancing for the edge appliances, in vendor-neutral form.',
    "# Map each entry onto the appliance's own terms: a pool with an HTTPS monitor, and a",
    '# global load balancing record whose members are withdrawn when the pool is unhealthy.',
    'services:',
  ];
  for (const { service, provide } of publishedVia(model, 'edge-adc')) {
    lines.push(
      `  - name: ${service.id}/${provide.name}`,
      `    frontend-port: ${provide['frontend-port'] ?? provide.port}`,
      '    pool:',
      ...service.instances.map((i) => `      - { site: ${i.site}, address: ${i.address}, port: ${provide.port} }`),
      '    monitor:                       # readiness, not "the TLS handshake worked" (RES-06)',
      '      protocol: https',
      '      method: GET',
      `      path: ${provide.health!.path}`,
      '      expect-status: 200',
      '      interval-seconds: 2',
      '      down-after-failures: 3',
      '      up-after-successes: 2',
      '    client-blocked-paths: [/health/]   # for the monitor only, never forwarded from clients (RES-08)',
      '    global:                        # DNS-based global load balancing (RES-02)',
      '      ttl-seconds: 30',
      '      withdraw-site-after-seconds: 60',
    );
  }
  // Internal applications get global load balancing too, on the appliances' DNS service:
  // a datacenter whose instances aren't ready is withdrawn for that application (RES-02).
  lines.push('internal-global:');
  for (const { service, provide } of publishedVia(model, 'platform-lb').filter((p) => p.service.kind !== 'database-cluster')) {
    const lb = model.services.get('platform-lb')!;
    lines.push(
      `  - name: ${service.id}.${DOMAIN}`,
      '    members:',
      ...lb.vips!.map((v) => `      - { site: ${v.site}, address: ${v.address}, port: ${provide['frontend-port'] ?? provide.port} }`),
      '    monitor:                       # the site\'s own instances, never the VIP: there, the other',
      '      protocol: https              # datacenter\'s backup servers would answer for a dead site',
      `      host: ${service.id}.${DOMAIN}`,
      `      path: ${provide.health!.path}`,
      '      expect-status: 200',
      '      interval-seconds: 5',
      '      targets:',
      ...lb.vips!.flatMap((v) => service.instances.filter((i) => i.site === v.site).map((i) => `        - { site: ${v.site}, address: ${i.address}, port: ${provide.health?.port ?? provide.port} }`)),
      '      withdraw-site-when: none of its targets is ready',
      '    ttl-seconds: 30',
      '    withdraw-site-after-seconds: 60',
    );
  }
  lines.push('');
  return lines.join('\n');
}

export function renderAll(model: Model): Map<string, string> {
  const files = new Map<string, string>();
  for (const site of ['dc1', 'dc2']) {
    files.set(`haproxy/platform-lb-${site}.cfg`, renderHaproxy(model, site));
    for (const node of model.services.get('platform-lb')!.instances.filter((i) => i.site === site)) {
      files.set(`keepalived/platform-lb-${node.address}.conf`, renderKeepalived(model, site, node.address));
    }
  }
  for (const s of model.services.values()) {
    if (s.kind === 'database-cluster' && s.replication) {
      files.set(`patroni/${s.id}.yml`, renderPatroni(model, s));
      files.set(`patroni/${s.id}.dcs.yml`, renderPatroniDcs(s));
      files.set(`pgbackrest/${s.id}.conf`, renderPgBackRest(model, s));
    }
  }
  files.set('etcd/rbac.yaml', renderEtcdRbac(model));
  files.set('edge/health-checks.yaml', renderEdgeSpec(model));
  files.set('failure-simulation.md', renderMarkdown(SCENARIOS.map((sc) => simulate(model.landscape, sc))));
  return files;
}

if (import.meta.main) {
  const files = renderAll(loadModel());
  rmSync(GENERATED, { recursive: true, force: true });
  for (const [path, content] of files) {
    mkdirSync(join(GENERATED, path, '..'), { recursive: true });
    writeFileSync(join(GENERATED, path), content);
  }
  console.log(`Wrote ${files.size} files to infrastructure/generated/.`);
}
