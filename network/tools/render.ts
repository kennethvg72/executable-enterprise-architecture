// Renders a compiled policy into the artifacts that enforce and test it:
// - an nftables ruleset per service (host firewall, inbound and outbound)
// - the HQ router's forward ruleset (HQ's own traffic, and DC1 <-> DC2 transit)
// - the egress proxy allowlist
// - a probe plan: thousands of connection attempts with their expected outcome
// - a readable table of every allowed flow

import type { Model, Service } from '../../enterprise-architecture/tools/lib/model.ts';
import { NATAX_SPACE, siteOf, within } from '../../enterprise-architecture/tools/lib/net.ts';
import { isAllowed, type Flow, type Policy } from './policy.ts';

const HEADER = '# Generated by network/tools/compile.ts from declared intent. Do not edit.\n';
const ANY = '0.0.0.0/0';

const set = (addresses: string[]) => (addresses.length === 1 ? addresses[0]! : `{ ${[...new Set(addresses)].sort().join(', ')} }`);
const comment = (text: string) => `comment "${text.replace(/"/g, "'").slice(0, 120)}"`;

/**
 * Merge flows with the same peer addresses and port into one rule line. A host with several
 * addresses (a load balancer node and its VIP) also matches its own side, so a flow to the VIP
 * doesn't open the node, and a flow to the node doesn't open the VIP.
 */
function rules(flows: Flow[], direction: 'saddr' | 'daddr', service?: Service): string[] {
  const seen = new Map<string, string>();
  for (const f of flows) {
    const peer = direction === 'saddr' ? f.from.addresses : f.to.addresses;
    const own = direction === 'saddr' ? f.to.addresses : f.from.addresses;
    const local = service?.vips ? `ip ${direction === 'saddr' ? 'daddr' : 'saddr'} ${set(own)} ` : '';
    const match = (peer.includes(ANY) ? `ip ${direction} != ${NATAX_SPACE} ` : `ip ${direction} ${set(peer)} `) + local;
    const key = `${match}${f.protocol ?? 'tcp'}${f.port}`;
    if (!seen.has(key)) seen.set(key, `    ${match}${f.protocol ?? 'tcp'} dport ${f.port} accept ${comment(f.purpose)}`);
  }
  return [...seen.values()];
}

/** Load balancer pairs share their VIP with VRRP (keepalived, unicast between the pair). */
function vrrp(service: Service, direction: 'saddr' | 'daddr'): string[] {
  if (!service.vips) return [];
  return [...new Set(service.instances.map((i) => i.site))].map((site) => {
    const pair = service.instances.filter((i) => i.site === site).map((i) => i.address);
    return `    ip ${direction} ${set(pair)} ip protocol vrrp accept ${comment(`VIP failover between the ${service.id} pair in ${site}`)}`;
  });
}

/**
 * ICMP: replies and errors for existing connections are "related" and pass with them. New ICMP is
 * only an echo request from the hosts that monitor (observability) and administer (PAWs); nothing
 * else, so ICMP isn't a channel between hosts that have no declared flow (ZTN-03).
 */
export function renderHostRuleset(service: Service, policy: Policy, pingers: string[] = []): string {
  const inbound = policy.flows.filter((f) => f.to.kind === 'service' && f.to.id === service.id);
  const outbound = policy.flows.filter((f) => f.from.kind === 'service' && f.from.id === service.id);
  return [
    HEADER,
    `# Service: ${service.id} (${(service.description ?? service.kind).trim().replace(/\s+/g, ' ')})`,
    `# Instances: ${service.instances.map((i) => `${i.address} (${i.site})`).join(', ')}`,
    '',
    'table inet natax {',
    '  chain input {',
    '    type filter hook input priority filter; policy drop;',
    '    ct state established,related accept',
    '    ct state invalid drop',
    '    iif lo accept',
    ...(pingers.length ? [`    ip saddr ${set(pingers)} ip protocol icmp icmp type echo-request accept comment "Monitoring and administration may ping (ZTN-03)"`] : []),
    ...rules(inbound, 'saddr', service),
    ...vrrp(service, 'saddr'),
    '    limit rate 10/second log prefix "natax-drop-in "   # then the policy drops it',
    '  }',
    '',
    '  chain output {',
    '    type filter hook output priority filter; policy drop;',
    '    ct state established,related accept',
    '    oif lo accept',
    ...(service.id === 'observability' ? ['    ip daddr 10.0.0.0/8 ip protocol icmp icmp type echo-request accept comment "Monitoring pings production hosts"'] : []),
    ...rules(outbound, 'daddr'),
    ...vrrp(service, 'daddr'),
    '    limit rate 10/second log prefix "natax-drop-out "',
    '  }',
    '}',
    '',
  ].join('\n');
}

/**
 * HQ's router forwards two kinds of traffic: traffic to and from HQ itself (the witness,
 * PAWs, staff devices), and DC1 <-> DC2 transit when the direct link is down (RES-04).
 * Transit must allow every declared flow between the datacenters, or losing the direct
 * link would break replication and quorum.
 */
export function renderHqRouter(model: Model, policy: Policy): string {
  const { sites } = model.landscape;
  const lines: string[] = [];
  const byTransit = sites['hq']?.transit ? transitFlows(model, policy) : [];
  for (const t of byTransit) {
    lines.push(`    ip saddr ${set(t.from)} ip daddr ${set(t.to)} ${t.protocol ?? 'tcp'} dport ${t.port} accept ${comment(`transit: ${t.purpose}`)}`);
  }
  const local: string[] = [];
  for (const f of policy.flows) {
    const fromHq = f.from.addresses.filter((a) => siteOf(a, sites) === 'hq' || isHqZone(model, a));
    const toHq = f.to.addresses.filter((a) => siteOf(a, sites) === 'hq');
    if (fromHq.length) local.push(`    ip saddr ${set(fromHq)} ip daddr ${set(f.to.addresses.filter((a) => siteOf(a, sites) !== 'hq'))} ${f.protocol ?? 'tcp'} dport ${f.port} accept ${comment(f.purpose)}`);
    if (toHq.length) local.push(`    ip saddr ${set(f.from.addresses.filter((a) => siteOf(a, sites) !== 'hq'))} ip daddr ${set(toHq)} ${f.protocol ?? 'tcp'} dport ${f.port} accept ${comment(f.purpose)}`);
  }
  return [
    HEADER,
    '# HQ router: forwards traffic to and from HQ, and DC1 <-> DC2 transit (RES-04).',
    '',
    'table inet natax-hq {',
    '  chain forward {',
    '    type filter hook forward priority filter; policy drop;',
    '    ct state established,related accept',
    '    ct state invalid drop',
    '',
    '    # DC1 <-> DC2 transit, used when the direct fiber is down.',
    ...lines,
    '',
    '    # Traffic to and from HQ.',
    ...[...new Set(local)].filter((l) => !l.includes('ip daddr  ') && !l.includes('ip saddr  ')),
    '    limit rate 10/second log prefix "natax-hq-drop "',
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Zones whose devices sit at HQ (PAWs, office devices), as opposed to VPN pools elsewhere. */
function isHqZone(model: Model, cidr: string): boolean {
  return cidr.includes('/') && within(cidr, model.landscape.sites['hq']!.prefix);
}

export interface TransitRule { from: string[]; to: string[]; port: number; protocol?: 'tcp' | 'udp'; purpose: string }

/** Every declared flow between the two datacenters, as the HQ router must forward it. */
export function transitFlows(model: Model, policy: Policy): TransitRule[] {
  const { sites } = model.landscape;
  const out: TransitRule[] = [];
  for (const f of policy.flows) {
    if (f.from.kind !== 'service' || f.to.kind !== 'service') continue;
    for (const [a, b] of [['dc1', 'dc2'], ['dc2', 'dc1']] as const) {
      const from = f.from.addresses.filter((x) => siteOf(x, sites) === a);
      const to = f.to.addresses.filter((x) => siteOf(x, sites) === b);
      if (from.length && to.length) out.push({ from, to, port: f.port, ...(f.protocol ? { protocol: f.protocol } : {}), purpose: f.purpose });
    }
  }
  return out;
}

export function renderEgressAllowlist(policy: Policy): string {
  const byService = new Map<string, { sources: string[]; destinations: Set<string> }>();
  for (const e of policy.egress) {
    const entry = byService.get(e.service) ?? { sources: e.sources, destinations: new Set<string>() };
    entry.destinations.add(`${e.fqdn}:${e.port}`);
    byService.set(e.service, entry);
  }
  const lines = [HEADER, '# Egress proxy: each service may reach only its declared externals (INT-05).', 'allow:'];
  for (const [service, e] of [...byService].sort(([a], [b]) => a.localeCompare(b))) {
    // Quoted: an unquoted "*.example" is a YAML alias, and the file wouldn't parse.
    lines.push(`  - service: ${service}`, `    sources: [${e.sources.join(', ')}]`, `    destinations: [${[...e.destinations].sort().map((d) => JSON.stringify(d)).join(', ')}]`);
  }
  lines.push('default: deny', '');
  return lines.join('\n');
}

export interface Probe {
  from: string;
  fromLabel: string;
  to: string;
  toLabel: string;
  port: number;
  expect: 'open' | 'blocked';
}

/** A representative address inside each zone, used as a probe vantage point. */
export const ZONE_VANTAGE: Record<string, string> = {
  internet: '203.0.113.10',
  workforce: '10.3.100.10',
  paw: '10.3.90.10',
  'test-acceptance': '10.1.60.10',
};

/**
 * The probe plan: from one instance of every service per site, and from each zone, try
 * every port of one instance of every service per site. Each probe expects what the
 * policy says. Positive probes prove legitimate traffic works; negative probes prove
 * everything else is blocked.
 */
export function probePlan(model: Model, policy: Policy): Probe[] {
  const perSite = (s: Service) => {
    const seen = new Set<string>();
    return (s.vips ?? s.instances).filter((i) => !seen.has(i.site) && seen.add(i.site));
  };
  const vantage: { address: string; label: string }[] = [];
  for (const s of model.services.values()) {
    const seen = new Set<string>();
    for (const i of s.egress ?? s.instances) if (!seen.has(i.site) && seen.add(i.site)) vantage.push({ address: i.address, label: s.id });
  }
  for (const [z, a] of Object.entries(ZONE_VANTAGE)) if (model.landscape.zones[z]) vantage.push({ address: a, label: `zone:${z}` });

  const targets: { address: string; label: string; ports: Set<number> }[] = [];
  // Probes are TCP connection attempts; UDP flows (DNS, NTP) are verified on the rules instead.
  const platformPorts = (model.landscape['platform-flows'] ?? []).filter((p) => p.to === 'all-production' && (p.protocol ?? 'tcp') === 'tcp').map((p) => p.port);
  // Load balancers listen on the frontend ports of everything published through them.
  const frontends = new Map<string, number[]>();
  for (const s of model.services.values()) {
    for (const p of s.provides ?? []) {
      if (p.via) frontends.set(p.via, [...(frontends.get(p.via) ?? []), p['frontend-port'] ?? p.port]);
    }
  }
  for (const s of model.services.values()) {
    const ports = new Set<number>([
      ...(s.provides ?? []).flatMap((p) => [p.port, ...(p.health ? [p.health.port] : [])]),
      ...(frontends.get(s.id) ?? []),
      ...(s.appliance ? [] : platformPorts),
    ]);
    for (const i of perSite(s)) targets.push({ address: i.address, label: s.id, ports });
    if (s.vips) for (const i of s.instances.filter((x, k, all) => all.findIndex((y) => y.site === x.site) === k)) targets.push({ address: i.address, label: `${s.id} (node)`, ports });
  }

  const probes: Probe[] = [];
  for (const v of vantage) {
    for (const t of targets) {
      if (t.address === v.address) continue;
      for (const port of t.ports) {
        probes.push({ from: v.address, fromLabel: v.label, to: t.address, toLabel: t.label, port, expect: isAllowed(policy, v.address, t.address, port) ? 'open' : 'blocked' });
      }
    }
  }
  return probes;
}

export function renderFlowTable(policy: Policy): string {
  const name = (e: Flow['from']) => (e.kind === 'zone' ? `zone:${e.id}` : e.id);
  const rows = policy.flows
    .map((f) => `| ${name(f.from)} | ${name(f.to)} | ${f.port} | ${f.purpose} | ${f.declaredIn} |`)
    .sort();
  return [
    '<!-- Generated by network/tools/compile.ts. Do not edit. -->',
    '# Allowed flows',
    '',
    `Every connection NATAX production allows: ${rows.length} flows. Everything else is denied.`,
    '',
    '| From | To | Port | Purpose | Declared in |',
    '|---|---|---|---|---|',
    ...[...new Set(rows)],
    '',
  ].join('\n');
}
